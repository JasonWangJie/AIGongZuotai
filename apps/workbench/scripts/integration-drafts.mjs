function client() {
  let cookie = '';
  return async (path, options = {}) => {
    const { expected = 200, body, project, key, ...rest } = options;
    const response = await fetch(new URL('/api/v1' + path, base), { ...rest, headers: { 'Content-Type': 'application/json', Origin: base.origin, ...(cookie ? { Cookie: cookie } : {}), ...(project ? { 'X-Project-ID': project } : {}), ...(key ? { 'Idempotency-Key': key } : {}) }, body: body === undefined ? undefined : JSON.stringify(body), signal: AbortSignal.timeout(12000) });
    assert.equal(response.status, expected, `${rest.method || 'GET'} ${path}: unexpected status ${response.status}`);
    const setCookie = response.headers.get('set-cookie');
    if (setCookie) { assert.match(setCookie, /httponly/i); cookie = setCookie.split(';')[0]; }
    const text = await response.text();
    return { data: text ? JSON.parse(text) : null, replay: response.headers.get('Idempotency-Replayed') };
  };
}
